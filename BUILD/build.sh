#!/usr/bin/env bash
# Rebuild BUILD/winz-advocate-knowledge.md from the source files.
# Run from the project root:  bash BUILD/build.sh
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=BUILD/winz-advocate-knowledge.md

FILES=(
  knowledge/entitlements/overview.md
  knowledge/entitlements/accommodation-supplement.md
  knowledge/entitlements/disability-allowance.md
  knowledge/entitlements/special-needs-grant-food.md
  knowledge/entitlements/jobseeker-support.md
  knowledge/entitlements/sole-parent-support.md
  knowledge/entitlements/supported-living-payment.md
  knowledge/entitlements/temporary-additional-support.md
  knowledge/entitlements/childcare-assistance.md
  knowledge/entitlements/working-for-families.md
  knowledge/entitlements/advance-payment-and-recoverable-assistance.md
  knowledge/entitlements/other-special-needs-grants.md
  knowledge/entitlements/emergency-housing.md
  knowledge/entitlements/emergency-benefit.md
  knowledge/entitlements/commonly-missed.md
  knowledge/process/contacting-your-case-manager.md
  knowledge/process/earning-while-on-a-benefit.md
  knowledge/process/benefit-stand-downs.md
  knowledge/process/your-rights-and-how-to-push-back.md
  knowledge/process/2025-rule-changes.md
  knowledge/process/overpayments-and-debt.md
  knowledge/process/being-investigated-for-fraud.md
  knowledge/process/review-of-decision.md
  knowledge/precedents.md
  knowledge/how-winz-operates.md
  knowledge/templates/email-request-food-grant-and-appointment.md
  knowledge/templates/email-follow-up-on-delay.md
  knowledge/templates/review-of-decision-request.md
  knowledge/templates/overpayment-and-debt-requests.md
  knowledge/support-network.md
  knowledge/community-notes/README.md
  prompt/intake-script.md
  case-file-template/case-file.md
)

# Any real community notes (files named note-*.md) get appended too.
for n in knowledge/community-notes/note-*.md; do
  [ -e "$n" ] && FILES+=("$n")
done

{
  echo "# WINZ Advocate — Knowledge Pack"
  echo
  echo "_Auto-built from the source files. Do not edit this file directly — edit the"
  echo "source files and rebuild with \`bash BUILD/build.sh\`._"
  echo
  echo "Built: $(date +%Y-%m-%d)"
  echo
  for f in "${FILES[@]}"; do
    echo
    echo "---"
    echo
    echo "<!-- FILE: $f -->"
    echo
    cat "$f"
    echo
  done
} > "$OUT"

echo "Wrote $OUT ($(wc -l < "$OUT") lines)"

# Also build a single paste-once file: instructions + knowledge pack together.
FULL=BUILD/winz-advocate-full-prompt.md
{
  cat BUILD/winz-advocate-instructions.md
  printf '\n\n============ KNOWLEDGE PACK ============\n\n'
  cat "$OUT"
} > "$FULL"
echo "Wrote $FULL ($(wc -l < "$FULL") lines)"
